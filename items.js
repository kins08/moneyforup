/** Нормализация названия: клиент присылает «Кейс: Первый шаг» */
function normName(s) {
  return String(s || '').trim().toLowerCase()
    .replace(/^кейс[\s:—-]*/i, '')
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim();
}

const CASE_BY_NAME = new Map();
for (const c of Object.values(CASES)) CASE_BY_NAME.set(normName(c.name), c);

/** Находит кейс по названию от клиента. null — это не кейс. */
function findCaseByName(rawName) {
  const key = String(rawName || '').toLowerCase();
  if (!key.includes('кейс')) return null;          // «Кейс: X» — только так кейсы и приходят
  return CASE_BY_NAME.get(normName(rawName)) || null;
}

/** Находит кейс по id (для внутренних вызовов) */
function getCase(caseId) { return CASES[caseId] || null; }

/** Предмет по коду 'case_500#3' */
function getItem(caseId, index) {
  const c = CASES[caseId];
  return c ? (c.items[index] || null) : null;
}

